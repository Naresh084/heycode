def parse_session_contracts() -> tuple[list[str], list[str], dict[str, str]]:
    """Parse closed kind lists and enum documentation."""

    text = read(SESSION_EVENT_SOURCE)
    v1 = parse_string_array(text, "KNOWN_KINDS_V1")
    v2 = parse_string_array(text, "KNOWN_KINDS_V2")
    body = balanced_body(text, "enum SessionEventKind")
    docs_by_tag: dict[str, str] = {}
    docs: list[str] = []
    pending_tag: str | None = None
    for raw_line in body.splitlines():
        line = raw_line.strip()
        if line.startswith("///"):
            docs.append(line[3:].strip())
            continue
        rename = re.match(r'#\[serde\(rename = "([^"]+)"\)\]', line)
        if rename:
            pending_tag = rename.group(1)
            continue
        if pending_tag is not None and re.match(r"[A-Z][A-Za-z0-9_]+", line):
            summary = " ".join(docs).strip()
            if not summary:
                raise GenerationError(f"session kind {pending_tag} has no documentation")
            docs_by_tag[pending_tag] = summary
            pending_tag = None
            docs = []
            continue
        if line and not line.startswith("#["):
            docs = []
    if set(docs_by_tag) != set(v2):
        missing = sorted(set(v2) - set(docs_by_tag))
        extra = sorted(set(docs_by_tag) - set(v2))
        raise GenerationError(f"session kind/doc drift: missing={missing}, extra={extra}")
    if not set(v1).issubset(v2):
        raise GenerationError("v1 kind set is not a subset of v2")
    return v1, v2, docs_by_tag


def render_session_events() -> str:
    """Render the closed session event vocabulary."""

    sources = [SESSION_EVENT_SOURCE]
    text = read(SESSION_EVENT_SOURCE)
    v1, v2, docs = parse_session_contracts()
    rows = ["| Kind | Readable envelope versions | Payload role |", "|---|---|---|"]
    for tag in v2:
        versions = "v1, v2" if tag in v1 else "v2 only"
        rows.append(f"| `{tag}` | {versions} | {docs[tag]} |")
    reasons = enum_values(text, "TurnEndReason", "snake_case")
    min_match = re.search(r"MIN_SESSION_LOG_VERSION: u8 = (\d+);", text)
    current_match = re.search(r"CURRENT_SESSION_LOG_VERSION: u8 = (\d+);", text)
    if min_match is None or current_match is None:
        raise GenerationError("session version constants changed")
    return (
        generated_header("Session event reference", sources)
        + f"This reader accepts envelope versions **{min_match.group(1)} through "
        f"{current_match.group(1)}**. New appends always use the current version; opening a "
        "historical log preserves its original bytes. Unknown kinds fail loud.\n\n"
        + "\n".join(rows)
        + "\n\n## Turn settlement reasons\n\n"
        + ", ".join(f"`{reason}`" for reason in reasons)
        + ".\n\n"
        + "This page enumerates wire vocabulary, not model visibility. Route-aware request "
        "projection decides which neutral messages, exact provider state, attachments, and "
        "compaction checkpoint form a particular request.\n"
    )


def render_all() -> dict[Path, str]:
    """Render every generated reference exactly once."""

    rendered = {
        Path("docs/reference/commands.md"): render_commands(),
        Path("docs/reference/configuration.md"): render_configuration(),
        Path("docs/reference/plugins.md"): render_plugins(),
        Path("docs/reference/session-events.md"): render_session_events(),
    }
    if set(rendered) != OUTPUTS:
        raise GenerationError("generated output registry drift")
    return rendered


def write_all(rendered: dict[Path, str]) -> None:
    """Write rendered references."""

    for path, content in rendered.items():
        destination = ROOT / path
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(content, encoding="utf-8")


def check_all(rendered: dict[Path, str]) -> list[str]:
    """Return stale/missing outputs without mutating the tree."""

    stale: list[str] = []
    for path, content in rendered.items():
        destination = ROOT / path
        try:
            current = destination.read_text(encoding="utf-8")
        except OSError:
            stale.append(f"missing {path}")
            continue
        if current != content:
            stale.append(f"stale {path}")
    return stale


def main() -> int:
    """CLI entry point."""

    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="regenerate checked-in references")
    mode.add_argument("--check", action="store_true", help="fail when references are stale")
    args = parser.parse_args()
    try:
        rendered = render_all()
        if args.write:
            write_all(rendered)
            for path in sorted(rendered, key=lambda item: item.as_posix()):
                print(f"generated {path}")
            return 0
        stale = check_all(rendered)
        if stale:
            for item in stale:
                print(item, file=sys.stderr)
            print(
                "regenerate with python3 scripts/generate_doc_references.py --write",
                file=sys.stderr,
            )
            return 1
        print(f"generated references fresh: {len(rendered)}")
        return 0
    except GenerationError as error:
        print(f"documentation generation failed: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
