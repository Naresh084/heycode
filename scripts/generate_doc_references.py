#!/usr/bin/env python3
"""Generate checked-in heycode reference pages from Rust source contracts.

The generator is intentionally standard-library-only.  It does not execute the
product or contact a provider.  Each parser is narrow and fails when the source
shape it consumes changes, turning descriptor drift into an explicit docs task.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
from dataclasses import dataclass
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]

COMMAND_PROJECTION = Path("crates/heycode-cli/tests/it/composition.rs")
CONFIG_SOURCE = Path("crates/heycode-config/src/lib.rs")
CONFIG_MIGRATION_SOURCE = Path("crates/heycode-config/src/migration.rs")
PROFILE_SOURCE = Path("crates/heycode-config/src/profiles.rs")
INVENTORY_PROJECTION = Path("crates/heycode-cli/tests/it/plugin_inventory.rs")
COMPOSITION_SOURCE = Path("crates/heycode-cli/src/lib.rs")
CORE_DESCRIPTOR_SOURCE = Path("crates/heycode-core/src/descriptor.rs")
CORE_INVENTORY_SOURCE = Path("crates/heycode-core/src/inventory.rs")
MANIFEST_WIRE_SOURCE = Path("crates/heycode-extensions/src/wire.rs")
MANIFEST_MODEL_SOURCE = Path("crates/heycode-extensions/src/model.rs")
MANIFEST_FIXTURE = Path("crates/heycode-extensions/tests/fixtures/plugin-v1.toml")
