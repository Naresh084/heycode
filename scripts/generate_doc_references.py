        + "\n".join(order_rows)
        + "\n\n## Descriptor and inventory vocabulary\n\n"
        + "Broad descriptor families: "
        + ", ".join(f"`{value}`" for value in broad)
        + ".\n\nExact inventory namespaces: "
        + ", ".join(f"`{value}`" for value in exact)
        + ".\n\nBroad families state what a plugin may contribute. Exact inventory states "
        "which named service, command, tool, provider, process, or other row a committed "
        "activation actually owns.\n\n"
        + "## External plugin manifest v1\n\n"
        + "The manifest is strict (`deny_unknown_fields`). Fields classified optional are "
        "the only fields whose Rust wire type is `Option`; arrays remain required even when empty.\n\n"
        + "\n".join(manifest_rows)
        + "\n\n### Closed manifest vocabulary\n\n"
