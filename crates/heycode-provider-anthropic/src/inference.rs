/// The narrower of two replay-safety proofs.
///
/// Replay safety is evidence, never preference: two resolvers that each saw
/// part of the request may only ever agree on the least permissive proof.
fn narrower_safety(left: RetrySafety, right: RetrySafety) -> RetrySafety {
    if replay_rank(left) <= replay_rank(right) {
        left
    } else {
        right
    }
}

/// Order replay safety from the least to the most permissive proof.
const fn replay_rank(safety: RetrySafety) -> u8 {
    match safety {
        RetrySafety::Never => 0,
        RetrySafety::DefinitiveFailuresOnly => 1,
        RetrySafety::StatelessPreOutput => 2,
    }
}

/// Index of the first input belonging to the current assistant turn.
///
/// A tool result is a `user` message on the wire but continues the turn it
/// belongs to, so only a standard user message opens a new one.
fn current_turn_start(inputs: &[InferenceInput]) -> usize {
    inputs
        .iter()
        .rposition(
            |input| matches!(input, InferenceInput::Message(message) if message.role == Role::User),
        )
        .map_or(0, |index| index.saturating_add(1))
}

fn state_content(state: &heycode_core::ProviderStateItem) -> &[serde_json::Value] {
    state
        .data()
        .get("content")
        .and_then(serde_json::Value::as_array)
        .map_or(&[], Vec::as_slice)
}

fn block_type(block: &serde_json::Value) -> Option<&str> {
    block.get("type").and_then(serde_json::Value::as_str)
}

const fn is_thinking_block(block_type: &str) -> bool {
    matches!(block_type.as_bytes(), b"thinking" | b"redacted_thinking")
}

/// Reject a replayed thinking block whose opaque continuity field is gone.
///
/// An empty `thinking` field is legitimate: with `display: "omitted"` the
/// server returns "thinking blocks ... with an empty `thinking` field" while
/// "the `signature` field still carries the encrypted full thinking". Only the
/// opaque field is load-bearing, so only the opaque field is checked.
fn validate_thinking_integrity(block: &serde_json::Value) -> Result<(), ResolveError> {
    let opaque = match block_type(block) {
        Some("thinking") => "signature",
        Some("redacted_thinking") => "data",
        _ => return Ok(()),
    };
    if block
        .get(opaque)
        .and_then(serde_json::Value::as_str)
        .is_none_or(str::is_empty)
    {
        return Err(invalid_state(
            "replayed Messages thinking block lost its opaque continuity field",
        ));
    }
    Ok(())
}

fn invalid_state(message: &str) -> ResolveError {
    ResolveError::InvalidRequest {
        field: "provider_state",
        message: message.to_owned(),
    }
}

struct ResponseMetadataStreamState {
    stream: InferenceStream,
    observed: ObservedResponse,
    ledger: ResponseMetadataLedger,
    expect_context_editing: bool,
    expect_cache_usage: bool,
    response_id: Option<String>,
    pending: Option<AnthropicResponseMetadata>,
    normalized_usage: Option<TokenUsage>,
    queued: Option<InferenceEvent>,
    terminal: bool,
}

fn with_response_metadata(
    stream: InferenceStream,
    observed: ObservedResponse,
    ledger: ResponseMetadataLedger,
    expect_context_editing: bool,
    expect_cache_usage: bool,
) -> InferenceStream {
    if !expect_context_editing && !expect_cache_usage {
        return stream;
    }
    Box::pin(futures::stream::unfold(
        ResponseMetadataStreamState {
            stream,
            observed,
            ledger,
            expect_context_editing,
            expect_cache_usage,
            response_id: None,
            pending: None,
            normalized_usage: None,
            queued: None,
            terminal: false,
        },
        |mut state| async move {
            if state.terminal {
                return None;
            }
            if let Some(event) = state.queued.take() {
                return Some((Ok(event), state));
            }
            let item = state.stream.next().await?;
            let event = match item {
                Ok(event) => event,
                Err(error) => {
                    state.terminal = true;
                    return Some((Err(error), state));
                }
            };
            match &event {
                InferenceEvent::ResponseStarted { response_id } => {
                    state.response_id = Some(response_id.clone());
                }
                InferenceEvent::ProviderState(_) => {
                    let observed = state.observed.snapshot();
                    if observed.response_id != state.response_id {
                        state.terminal = true;
                        return Some((Err(metadata_error()), state));
                    }
                    let metadata = match response_metadata_from_observation(
                        &observed,
                        state.expect_context_editing,
                        state.expect_cache_usage,
                    ) {
                        Ok(metadata) => metadata,
                        Err(error) => {
                            state.terminal = true;
                            return Some((Err(error), state));
                        }
                    };
                    state.pending = Some(metadata);
                }
                InferenceEvent::Usage(usage) => {
                    state.normalized_usage = Some(*usage);
                    let Some(metadata) = state.pending.as_ref() else {
                        state.terminal = true;
                        return Some((Err(metadata_error()), state));
                    };
                    if let Some(cache) = metadata.cache_usage()
                        && (cache.total_input_tokens() != usage.prompt_tokens
                            || cache.output_tokens() != usage.completion_tokens)
                    {
                        state.terminal = true;
                        return Some((Err(metadata_error()), state));
                    }
                    let neutral = match neutral_response_metadata(metadata) {
                        Ok(metadata) => metadata,
                        Err(error) => {
                            state.terminal = true;
                            return Some((Err(error), state));
                        }
                    };
                    state.queued = Some(event);
                    return Some((Ok(InferenceEvent::ResponseMetadata(neutral)), state));
                }
                InferenceEvent::Finish(_) => {
                    let Some(response_id) = state.response_id.clone() else {
                        state.terminal = true;
                        return Some((Err(metadata_error()), state));
                    };
                    let Some(metadata) = state.pending.take() else {
                        state.terminal = true;
                        return Some((Err(metadata_error()), state));
                    };
                    if let Some(cache) = metadata.cache_usage() {
                        let Some(normalized) = state.normalized_usage else {
                            state.terminal = true;
                            return Some((Err(metadata_error()), state));
                        };
                        if cache.total_input_tokens() != normalized.prompt_tokens
                            || cache.output_tokens() != normalized.completion_tokens
                        {
                            state.terminal = true;
                            return Some((Err(metadata_error()), state));
                        }
                    }
                    state.ledger.insert(response_id, metadata);
                    state.terminal = true;
                }
                InferenceEvent::ItemStarted { .. }
                | InferenceEvent::TextDelta(_)
                | InferenceEvent::ReasoningDelta(_)
                | InferenceEvent::ToolCallDelta { .. }
                | InferenceEvent::ServerToolCall { .. }
                | InferenceEvent::ServerToolResult { .. }
                | InferenceEvent::ServerToolUsage(_)
                | InferenceEvent::Citation { .. }
                | InferenceEvent::ItemFinished { .. }
                | InferenceEvent::ResponseFinished { .. } => {}
                InferenceEvent::ResponseMetadata(_) => {
                    state.terminal = true;
                    return Some((Err(metadata_error()), state));
                }
            }
            Some((Ok(event), state))
        },
    ))
}

fn neutral_response_metadata(
    metadata: &AnthropicResponseMetadata,
) -> Result<heycode_core::ProviderResponseMetadata, LlmError> {
    let cache = metadata
        .cache_usage()
        .map(|cache| {
            let usage = heycode_core::ProviderCacheUsage::new(
                cache.total_input_tokens(),
                cache.output_tokens(),
                cache.cache_read_input_tokens(),
                cache.cache_creation_input_tokens(),
            )
            .and_then(|usage| usage.with_uncached_input_tokens(cache.uncached_input_tokens()))?;
            match (
                cache.cache_creation_5m_input_tokens(),
                cache.cache_creation_1h_input_tokens(),
            ) {
                (Some(five), Some(hour)) => usage.with_cache_write_ttl_tokens(five, hour),
                (None, None) => Ok(usage),
                _ => Err(heycode_core::ProviderResponseMetadataError::InvalidCacheUsage),
            }
        })
        .transpose()
        .map_err(|_| metadata_error())?;
    let (edits, impact) = metadata
        .context_editing()
        .map_or_else(
            || Ok((Vec::new(), None)),
            |report| {
                let edits = report
                    .edits()
                    .iter()
                    .map(|edit| {
                        let kind = match edit.kind() {
                            crate::AnthropicContextEditKind::ClearThinking => {
                                heycode_core::ContextEditKind::ClearThinking
                            }
                            crate::AnthropicContextEditKind::ClearToolUses => {
                                heycode_core::ContextEditKind::ClearToolUses
                            }
                        };
                        heycode_core::ProviderContextEdit::new(
                            kind,
                            edit.cleared_units(),
                            edit.cleared_input_tokens(),
                        )
                    })
                    .collect::<Result<Vec<_>, _>>()?;
                let impact = match report.cache_impact() {
                    crate::AnthropicCacheImpact::Preserved => {
                        heycode_core::CachePrefixImpact::Preserved
                    }
                    crate::AnthropicCacheImpact::InvalidatedAtEdit => {
                        heycode_core::CachePrefixImpact::InvalidatedAtEdit
                    }
                };
                Ok((edits, Some(impact)))
            },
        )
        .map_err(|_: heycode_core::ProviderResponseMetadataError| metadata_error())?;
    heycode_core::ProviderResponseMetadata::new(cache, edits, impact).map_err(|_| metadata_error())
}

fn response_metadata_from_observation(
    observed: &ObservedResponseState,
    expect_context_editing: bool,
    expect_cache_usage: bool,
) -> Result<AnthropicResponseMetadata, LlmError> {
    let context_editing = if expect_context_editing {
        let context = observed
            .context_management
            .clone()
            .ok_or_else(metadata_error)?;
        Some(
            AnthropicContextEditReport::from_terminal(
                &serde_json::json!({"context_management":context}),
            )
            .map_err(|_| metadata_error())?,
        )
    } else {
        None
    };
    let cache_usage = if expect_cache_usage {
        Some(
            AnthropicCacheUsage::from_usage(observed.usage.as_ref().ok_or_else(metadata_error)?)
                .map_err(|_| metadata_error())?,
        )
    } else {
        None
    };
    Ok(AnthropicResponseMetadata::new(context_editing, cache_usage))
}

fn compaction_resolve_error(error: AnthropicCompactionFault, model: &str) -> ResolveError {
    match error {
        AnthropicCompactionFault::UnsupportedCapability => ResolveError::Unsupported {
            provider: ANTHROPIC_PROVIDER.to_owned(),
            model: model.to_owned(),
            capability: heycode_llm::RequestedCapability::NativeCompaction,
        },
        AnthropicCompactionFault::UnprovenCapability => ResolveError::Unproven {
            provider: ANTHROPIC_PROVIDER.to_owned(),
            model: model.to_owned(),
            capability: heycode_llm::RequestedCapability::NativeCompaction,
        },
        AnthropicCompactionFault::InvalidConfiguration
        | AnthropicCompactionFault::WrongRoute
        | AnthropicCompactionFault::InvalidState => ResolveError::InvalidRequest {
            field: "native_features",
            message: "Anthropic native compaction configuration is invalid".to_owned(),
        },
    }
}

