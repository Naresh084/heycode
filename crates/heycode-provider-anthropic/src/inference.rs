//! Provider-owned Anthropic inference wiring and thinking-state policy.
//!
//! PAN01 shipped identity, auth and discovery but nothing that could dispatch.
//! PAN02 adds the route over the reusable `AnthropicMessagesAdapter` that P05
//! owns, and the requirement that route enforces on replay: an assistant turn
//! waiting on client tool results must come back carrying its own thinking
//! blocks, signatures intact.
//!
//! The rules encoded here are quoted from the vendor documentation rather than
//! inferred:
//!
//! * "when you return tool results, you must pass the thinking blocks from the
//!   assistant message back to the API, complete and unmodified"
//!   <https://platform.claude.com/docs/en/build-with-claude/thinking#thinking-with-tool-use>
//! * "Required: within a tool-use turn, pass thinking blocks back. Recommended:
//!   across turns, pass everything back. Allowed: outside tool use, omit prior
//!   turns' thinking."
//!   <https://platform.claude.com/docs/en/build-with-claude/thinking#preserving-thinking-blocks>
//! * "Full thinking content is encrypted and returned in the `signature` field
//!   on each thinking block. The API uses the signature to verify that thinking
//!   blocks were generated by Claude when you pass them back."
//!   <https://platform.claude.com/docs/en/build-with-claude/thinking#thinking-encryption>
//! * "In extended (manual) mode, the API additionally enforces that the final
//!   assistant turn of a thinking-enabled request begins with a thinking block.
//!   Adaptive mode relaxes this."
//!   <https://platform.claude.com/docs/en/build-with-claude/thinking#thinking-with-tool-use>
//!
//! The failure this row exists to prevent is silent: a mid-turn thinking
//! mismatch is not an error. "If you toggle thinking mid-turn (for example,
//! between sending a tool call and returning its result), the API doesn't
//! error. Instead, it silently disables thinking for that request." Enforcing
//! locally turns an invisible quality regression into a loud local failure with
//! no request bytes sent.

