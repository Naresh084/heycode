fn map_native_compaction_error(
    error: &LlmError,
    cancellation: &tokio_util::sync::CancellationToken,
) -> NativeCompactionError {
    if cancellation.is_cancelled() || error.class() == ProviderErrorClass::Cancelled {
        NativeCompactionError::Cancelled
    } else {
        match error.class() {
            ProviderErrorClass::Protocol | ProviderErrorClass::Overflow => {
                NativeCompactionError::InvalidCheckpoint
            }
            ProviderErrorClass::Authentication
            | ProviderErrorClass::ContextWindowExceeded
            | ProviderErrorClass::Conflict
            | ProviderErrorClass::InvalidRequest => NativeCompactionError::Rejected,
            ProviderErrorClass::RateLimited
            | ProviderErrorClass::Overloaded
            | ProviderErrorClass::Server
            | ProviderErrorClass::Timeout
            | ProviderErrorClass::Network => NativeCompactionError::Transport,
            ProviderErrorClass::Cancelled => NativeCompactionError::Cancelled,
        }
    }
}

